#!/usr/bin/env node
/*
 * Generates the bundled web fonts module (blueprint RENDERING/01 → Fonts):
 *   apps/desktop/src/renderer/lib/bundled-fonts.ts   FontFace registrations for the renderer
 *   packages/protocol/src/fonts.ts                   the family list agents and the font picker see
 *   packages/core/src/text-metrics-data.ts           advance widths per family and weight (fontkit instances of the
 *                                                    same files), so the core lays text out with the widths the canvas
 *                                                    draws (blueprint DOCUMENT_MODEL/03 → Text measure)
 * Faces come from the OFL @fontsource packages in apps/desktop devDependencies, latin + latin-ext only.
 * Registered under the family's real name ("Inter Tight", not "Inter Tight Variable"), so a design
 * that names the font draws with it and its HTML export loads the same font from Google Fonts.
 *
 *   node scripts/gen-fonts.mjs
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as fontkit from 'fontkit';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const modules = join(root, 'node_modules');

/** Family name → package; variable packages cover 100–900, the rest list their weights. */
const FAMILIES = [
  ['Inter', '@fontsource-variable/inter'],
  ['Inter Tight', '@fontsource-variable/inter-tight'],
  ['Geist', '@fontsource-variable/geist'],
  ['Geist Mono', '@fontsource-variable/geist-mono'],
  ['DM Sans', '@fontsource-variable/dm-sans'],
  ['Manrope', '@fontsource-variable/manrope'],
  ['Plus Jakarta Sans', '@fontsource-variable/plus-jakarta-sans'],
  ['Space Grotesk', '@fontsource-variable/space-grotesk'],
  ['Outfit', '@fontsource-variable/outfit'],
  ['Sora', '@fontsource-variable/sora'],
  ['Instrument Sans', '@fontsource-variable/instrument-sans'],
  ['Bricolage Grotesque', '@fontsource-variable/bricolage-grotesque'],
  ['Fraunces', '@fontsource-variable/fraunces'],
  ['Playfair Display', '@fontsource-variable/playfair-display'],
  ['Instrument Serif', '@fontsource/instrument-serif'],
  ['JetBrains Mono', '@fontsource-variable/jetbrains-mono'],
];
const SUBSETS = ['latin', 'latin-ext'];

/** unicode-range of each face file, read from the package's own CSS (comment above each @font-face names the file). */
function ranges(pkg) {
  const out = new Map();
  for (const css of ['index.css', 'wght.css', 'wght-italic.css', '400.css', '400-italic.css']) {
    const file = join(modules, pkg, css);
    if (!existsSync(file)) continue;
    const text = readFileSync(file, 'utf8');
    for (const m of text.matchAll(/\/\*\s*([a-z0-9-]+)\s*\*\/\s*@font-face\s*\{([^}]*)\}/g)) {
      const range = /unicode-range:\s*([^;]+);/.exec(m[2]);
      if (range) out.set(m[1], range[1].trim());
    }
  }
  return out;
}

const imports = [];
const faces = [];
const families = [];
let n = 0;
for (const [family, pkg] of FAMILIES) {
  const dir = join(modules, pkg, 'files');
  if (!existsSync(dir)) throw new Error(`${pkg} is not installed — corepack pnpm@9.15.0 install`);
  const slug = pkg.split('/')[1];
  const variable = pkg.startsWith('@fontsource-variable/');
  const r = ranges(pkg);
  let italic = false;
  for (const subset of SUBSETS) {
    for (const style of ['normal', 'italic']) {
      const stem = variable ? `${slug}-${subset}-wght-${style}` : `${slug}-${subset}-400-${style}`;
      if (!existsSync(join(dir, `${stem}.woff2`))) continue;
      if (style === 'italic') italic = true;
      const v = `f${n++}`;
      imports.push(`import ${v} from '${pkg}/files/${stem}.woff2?url';`);
      faces.push(`  [${JSON.stringify(family)}, ${v}, ${JSON.stringify(style)}, ${JSON.stringify(variable ? '100 900' : '400')}, ${JSON.stringify(r.get(stem) ?? '')}],`);
    }
  }
  families.push({ family, weights: variable ? '100–900' : '400', italic });
}

writeFileSync(join(root, 'apps/desktop/src/renderer/lib/bundled-fonts.ts'), `/* Generated by scripts/gen-fonts.mjs — do not edit by hand. */
${imports.join('\n')}

/** [family, url, style, weight range, unicode-range] */
const FACES: Array<[string, string, 'normal' | 'italic', string, string]> = [
${faces.join('\n')}
];

/** Registers the bundled faces once; the canvas loads each face the first time it draws with it. */
export function registerBundledFonts(): void {
  if (typeof document === 'undefined' || !document.fonts) return;
  for (const [family, url, style, weight, unicodeRange] of FACES) {
    document.fonts.add(new FontFace(family, \`url(\${url}) format("woff2")\`, { style, weight, ...(unicodeRange ? { unicodeRange } : {}), display: 'swap' }));
  }
}
`);

writeFileSync(join(root, 'packages/protocol/src/fonts.ts'), `/* Generated by scripts/gen-fonts.mjs — do not edit by hand. */

/** Fonts the app ships (OFL, from Google Fonts): they draw the same on every machine and export as Google Fonts links. */
export const BUNDLED_FONT_FAMILIES = ${JSON.stringify(families, null, 2).replace(/"(\w+)":/g, '$1:')} as const;

export const BUNDLED_FONTS: string[] = BUNDLED_FONT_FAMILIES.map((f) => f.family);
`);
/* ------------------------------ text metrics ------------------------------ */

/** Code point ranges that get a table; anything else is estimated by the core. */
const RANGES = [[0x20, 0x24f], [0x2000, 0x206f], [0x20a0, 0x20c0], [0x2100, 0x2122], [0x2190, 0x2199], [0x2212, 0x2215]];
const METRIC_WEIGHTS = [300, 400, 500, 600, 700, 800];
const metrics = {};
for (const [family, pkg] of FAMILIES) {
  const slug = pkg.split('/')[1];
  const variable = pkg.startsWith('@fontsource-variable/');
  const files = SUBSETS.map((subset) => join(modules, pkg, 'files', variable ? `${slug}-${subset}-wght-normal.woff2` : `${slug}-${subset}-400-normal.woff2`)).filter(existsSync);
  const fonts = files.map((f) => fontkit.create(readFileSync(f)));
  for (const weight of variable ? METRIC_WEIGHTS : [400]) {
    const inst = fonts.map((f) => (variable && f.variationAxes?.wght ? f.getVariation({ wght: weight }) : f));
    const upm = inst[0].unitsPerEm;
    const adv = [];
    for (const [a, b] of RANGES) {
      for (let cp = a; cp <= b; cp++) {
        let w = 0;
        for (const f of inst) {
          if (!f.hasGlyphForCodePoint(cp)) continue;
          w = Math.round(f.glyphForCodePoint(cp).advanceWidth);
          break;
        }
        adv.push(w);
      }
    }
    metrics[`${family}|${weight}`] = { upm, adv: adv.map((x) => x.toString(36)).join(',') };
  }
}
writeFileSync(join(root, 'packages/core/src/text-metrics-data.ts'), `/* Generated by scripts/gen-fonts.mjs (fontkit instances of the bundled woff2 faces; OFL). Do not edit. */
/** Code point ranges [first, last] that have advances, in table order. */
export const METRIC_RANGES: ReadonlyArray<readonly [number, number]> = ${JSON.stringify(RANGES)};
/** "Family|weight" → units per em and base-36 advance widths (0 = no glyph), one per code point in METRIC_RANGES. */
export const FONT_METRICS: Record<string, { upm: number; adv: string }> = ${JSON.stringify(metrics)};
`);

console.log(`bundled ${families.length} families, ${faces.length} faces, ${Object.keys(metrics).length} measured weights`);

// Generates, from one list of bundled fonts (all OFL, @fontsource static instances):
//   packages/core/src/text-metrics-data.ts       glyph advance widths, so the core lays text out with the
//                                                 widths the renderer draws (blueprint DOCUMENT_MODEL/03 → Text measure)
//   apps/desktop/src/renderer/lib/fonts-bundled.ts the @font-face imports the renderer ships (Latin + Latin Extended)
// Run: node scripts/gen-text-metrics.mjs   (needs the @fontsource packages below and opentype.js)
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import opentype from 'opentype.js';

const FAMILIES = {
  'Inter': 'inter', 'Inter Tight': 'inter-tight', 'Roboto': 'roboto', 'Open Sans': 'open-sans', 'Poppins': 'poppins',
  'Montserrat': 'montserrat', 'Plus Jakarta Sans': 'plus-jakarta-sans', 'DM Sans': 'dm-sans', 'Manrope': 'manrope',
  'Space Grotesk': 'space-grotesk', 'Playfair Display': 'playfair-display', 'JetBrains Mono': 'jetbrains-mono',
};
const WEIGHTS = [300, 400, 500, 600, 700, 800];
const SUBSETS = ['latin', 'latin-ext'];
/** Code point ranges that get a table; anything else falls back to an estimate. */
const RANGES = [[0x20, 0x24f], [0x2000, 0x206f], [0x20a0, 0x20c0], [0x2100, 0x2122], [0x2190, 0x2199], [0x2212, 0x2215]];

const dir = (slug) => join('node_modules', '@fontsource', slug);
const fonts = {};
const imports = [];
const faces = [];
for (const [family, slug] of Object.entries(FAMILIES)) {
  for (const weight of WEIGHTS) {
    const files = SUBSETS.map((sub) => join(dir(slug), 'files', `${slug}-${sub}-${weight}-normal.woff`));
    if (!existsSync(files[0])) continue; // this family has no such weight
    const parsed = files.filter(existsSync).map((file) => {
      const buf = readFileSync(file);
      return opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
    });
    const upm = parsed[0].unitsPerEm;
    const adv = [];
    for (const [a, b] of RANGES) {
      for (let cp = a; cp <= b; cp++) {
        let w = 0;
        for (const f of parsed) {
          const g = f.charToGlyph(String.fromCodePoint(cp));
          if (g && g.index !== 0) { w = g.advanceWidth; break; }
        }
        adv.push(w);
      }
    }
    fonts[`${family}|${weight}`] = { upm, adv: adv.map((n) => n.toString(36)).join(',') };
    for (const sub of SUBSETS) if (existsSync(join(dir(slug), `${sub}-${weight}.css`))) imports.push(`import '@fontsource/${slug}/${sub}-${weight}.css';`);
    faces.push([family, weight]);
  }
}

const versions = Object.values(FAMILIES).map((slug) => `${slug} ${JSON.parse(readFileSync(join(dir(slug), 'package.json'), 'utf8')).version}`).join(', ');
writeFileSync(join('packages', 'core', 'src', 'text-metrics-data.ts'),
  `/* Generated by scripts/gen-text-metrics.mjs from @fontsource (${versions}; OFL). Do not edit. */\n` +
  `/** Code point ranges [first, last] that have advances, in table order. */\n` +
  `export const METRIC_RANGES: ReadonlyArray<readonly [number, number]> = ${JSON.stringify(RANGES)};\n` +
  `/** "Family|weight" → units per em and base-36 advance widths (0 = no glyph), one per code point in METRIC_RANGES. */\n` +
  `export const FONT_METRICS: Record<string, { upm: number; adv: string }> = ${JSON.stringify(fonts)};\n`);
writeFileSync(join('apps', 'desktop', 'src', 'renderer', 'lib', 'fonts-bundled.ts'),
  `/* Generated by scripts/gen-text-metrics.mjs — the faces measured in packages/core/src/text-metrics-data.ts. Do not edit. */\n` +
  `${imports.join('\n')}\n\n` +
  `/** [family, weight] of every bundled face. */\n` +
  `export const BUNDLED_FACES: ReadonlyArray<readonly [string, number]> = ${JSON.stringify(faces)};\n`);
console.log(faces.length, 'faces,', imports.length, 'css imports');

// Generates packages/core/src/icons-data.ts from lucide (ISC licence): name → SVG path data on a 24×24 grid.
// Run: node scripts/gen-icons.mjs   (needs lucide-react installed in the workspace)
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = join('node_modules', 'lucide-react', 'dist', 'esm', 'icons');
const r = (v) => Math.round(Number(v) * 100) / 100;

const NUM = String.raw`[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?`;
const LEAD_MOVE = new RegExp(String.raw`^\s*m\s*(${NUM})[\s,]*(${NUM})[\s,]*`);

/**
 * A path's first `m` is absolute, but once paths are concatenated it would turn relative.
 * `m x y …pairs` → `M x y l …pairs`: the implicit pairs after a relative moveto stay relative linetos.
 */
function absoluteStart(d) {
  const m = LEAD_MOVE.exec(d);
  if (!m) return d;
  const rest = d.slice(m[0].length);
  return `M${m[1]} ${m[2]}${/^[-+.\d]/.test(rest) ? 'l' : ''}${rest}`;
}

/** lucide elements → one path string. Strokes only; lucide icons are drawn with stroke 2, round caps. */
function toD([tag, a]) {
  switch (tag) {
    case 'path': return absoluteStart(a.d);
    case 'line': return `M${r(a.x1)} ${r(a.y1)}L${r(a.x2)} ${r(a.y2)}`;
    case 'polyline':
    case 'polygon': {
      const pts = a.points.trim().split(/[\s,]+/).map(Number);
      let d = '';
      for (let i = 0; i < pts.length; i += 2) d += `${i ? 'L' : 'M'}${r(pts[i])} ${r(pts[i + 1])}`;
      return tag === 'polygon' ? `${d}Z` : d;
    }
    case 'circle': {
      const cx = r(a.cx), cy = r(a.cy), rr = r(a.r);
      return `M${r(cx - rr)} ${cy}a${rr} ${rr} 0 1 0 ${r(rr * 2)} 0a${rr} ${rr} 0 1 0 ${r(-rr * 2)} 0`;
    }
    case 'ellipse': {
      const cx = r(a.cx), cy = r(a.cy), rx = r(a.rx), ry = r(a.ry);
      return `M${r(cx - rx)} ${cy}a${rx} ${ry} 0 1 0 ${r(rx * 2)} 0a${rx} ${ry} 0 1 0 ${r(-rx * 2)} 0`;
    }
    case 'rect': {
      const x = r(a.x ?? 0), y = r(a.y ?? 0), w = r(a.width), h = r(a.height), rx = Math.min(r(a.rx ?? a.ry ?? 0), w / 2, h / 2);
      if (!rx) return `M${x} ${y}h${w}v${h}h${-w}Z`;
      return `M${r(x + rx)} ${y}h${r(w - 2 * rx)}a${rx} ${rx} 0 0 1 ${rx} ${rx}v${r(h - 2 * rx)}a${rx} ${rx} 0 0 1 ${-rx} ${rx}h${r(-(w - 2 * rx))}a${rx} ${rx} 0 0 1 ${-rx} ${-rx}v${r(-(h - 2 * rx))}a${rx} ${rx} 0 0 1 ${rx} ${-rx}Z`;
    }
    default: throw new Error(`unknown lucide element ${tag}`);
  }
}

// The data block is a plain object literal; evaluate just that literal (no React import needed).
const out = {};
for (const f of readdirSync(dir).filter((f) => f.endsWith('.mjs')).sort()) {
  const src = readFileSync(join(dir, f), 'utf8');
  const m = /const __iconData = (\{[\s\S]*?\n\});/.exec(src);
  if (!m) continue;
  const data = Function(`return (${m[1]});`)();
  out[data.name] = data.node.map(toD).join('');
}
const version = JSON.parse(readFileSync(join('node_modules', 'lucide-react', 'package.json'), 'utf8')).version;
writeFileSync(join('packages', 'core', 'src', 'icons-data.ts'),
  `/* Generated by scripts/gen-icons.mjs from lucide ${version} (ISC licence, https://lucide.dev/license). Do not edit. */\n` +
  `/** lucide icon name → SVG path data on a 24×24 grid, drawn as a 2px round stroke. */\n` +
  `export const ICONS: Record<string, string> = ${JSON.stringify(out)};\n`);
console.log(Object.keys(out).length, 'icons');

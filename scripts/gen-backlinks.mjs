// Writes a "Backlinks" block at the end of every docs/blueprint/**/*.md: which docs link to it and
// which source files it governs. Sources of a code backlink:
//   1. a `blueprint X/NN` (or `blueprint X`) comment in apps/, packages/ or scripts/;
//   2. a row of docs/blueprint/CODE_MAP/*.md that names the file and links the doc.
// Run: node scripts/gen-backlinks.mjs           regenerate blocks, print problems
//      node scripts/gen-backlinks.mjs --check   change nothing; exit 1 on stale blocks or problems
// Problems: broken relative links, `blueprint X/NN` comments that name no doc, source files missing
// from CODE_MAP, blueprint files over 150 lines (the generated block does not count).
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const BP = join(ROOT, 'docs', 'blueprint');
const CHECK = process.argv.includes('--check');
const START = '<!-- backlinks:start — generated by `node scripts/gen-backlinks.mjs`; do not edit by hand -->';
const END = '<!-- backlinks:end -->';
const BLOCK = /\n*<!-- backlinks:start[\s\S]*?<!-- backlinks:end -->\n?/;
const MAX_LINES = 150;
const SRC_DIRS = ['apps', 'packages', 'scripts'];
const SRC_EXT = /\.(ts|tsx|mjs)$/;
const SKIP_SRC = /(^|\/)(node_modules|dist|out|fixtures)\/|\.d\.ts$|icons-data\.ts$/;

const posix = (p) => p.split(sep).join('/');
const rel = (from, to) => { const r = posix(relative(dirname(from), to)); return r.startsWith('.') ? r : `./${r}`; };
const repo = (abs) => posix(relative(ROOT, abs));

function walk(dir, keep, out = []) {
  if (!existsSync(dir)) return out;
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) { if (name !== 'node_modules') walk(p, keep, out); } else if (keep(p)) out.push(p);
  }
  return out;
}

const mdFiles = [...walk(join(ROOT, 'docs'), (p) => p.endsWith('.md')), ...['CLAUDE.md', 'README.md'].map((f) => join(ROOT, f)).filter(existsSync)];
const bpFiles = mdFiles.filter((p) => p.startsWith(BP + sep));
const srcFiles = SRC_DIRS.flatMap((d) => walk(join(ROOT, d), (p) => SRC_EXT.test(p) && !SKIP_SRC.test(posix(p))));
/** Text with LF endings: a Windows checkout (core.autocrlf) has CRLF, git stores LF. */
const read = (p) => readFileSync(p, 'utf8').replace(/\r\n/g, '\n');
const body = (p) => read(p).replace(BLOCK, '\n');

/** Short label: `MCP/02` for a blueprint sub-file, `MCP` for a hub, `plan/CHAT_AGENT`, `CLAUDE.md`. */
function label(abs) {
  const r = repo(abs);
  if (r.startsWith('docs/blueprint/')) return r.slice(15).replace(/\.md$/, '').replace(/\/(\d\d)-[^/]*$/, '/$1');
  if (r.startsWith('docs/')) return r.slice(5).replace(/\.md$/, '');
  return r;
}

/** `blueprint <SECTION>/<NN>` → docs/blueprint/<SECTION>/<NN>-*.md; `blueprint <SECTION>` → docs/blueprint/<SECTION>.md. */
function resolveRef(section, part) {
  if (!part) { const hub = join(BP, `${section}.md`); return existsSync(hub) ? hub : null; }
  const dir = join(BP, section);
  if (!existsSync(dir)) return null;
  const hit = readdirSync(dir).find((f) => f.startsWith(`${part}-`) && f.endsWith('.md'));
  return hit ? join(dir, hit) : null;
}

const docLinks = new Map(bpFiles.map((p) => [p, new Set()]));
const codeLinks = new Map(bpFiles.map((p) => [p, new Set()]));
const problems = [];
const mapped = new Set();
const isCodeMap = (p) => repo(p).startsWith('docs/blueprint/CODE_MAP');
const isTopics = (p) => repo(p) === 'docs/blueprint/TOPICS.md';
const LINK = /\[[^\]]*\]\(([^)\s]+)\)/g;

for (const file of mdFiles) {
  const lines = body(file).split('\n');
  const hubDir = file.endsWith('.md') ? file.slice(0, -3) : file;
  let fenced = false;
  lines.forEach((line, i) => {
    if (/^\s*```/.test(line)) fenced = !fenced;
    if (fenced) return; // examples in code blocks are not links
    const targets = [];
    for (const m of line.replace(/`[^`]*`/g, '').matchAll(LINK)) {
      const href = m[1];
      if (/^(https?|mailto|archadev):|^#/.test(href)) continue;
      const abs = resolve(dirname(file), decodeURIComponent(href.split('#')[0]));
      if (!existsSync(abs)) { problems.push(`broken link  ${repo(file)}:${i + 1} → ${href}`); continue; }
      targets.push(abs);
    }
    if (isCodeMap(file) && line.startsWith('|')) {
      // A CODE_MAP row: every code link in it is governed by every blueprint link in the same row.
      const code = targets.filter((t) => !t.endsWith('.md') && statSync(t).isFile());
      for (const c of code) {
        mapped.add(c);
        for (const t of targets) if (codeLinks.has(t) && !isCodeMap(t)) codeLinks.get(t).add(c);
      }
      return;
    }
    if (line.startsWith('←') || isCodeMap(file) || isTopics(file)) return; // breadcrumbs and indexes are navigation, not references
    for (const t of targets) {
      if (!docLinks.has(t) || t === file) continue;
      if (t.startsWith(hubDir + sep)) continue; // a hub's own parts table
      if (repo(file) === 'docs/blueprint/INDEX.md' && dirname(t) === BP) continue; // INDEX document map
      docLinks.get(t).add(file);
    }
  });
}

const REF = /blueprint ([A-Z][A-Z_]+)(?:\/(\d\d))?/g;
for (const file of srcFiles) {
  const src = readFileSync(file, 'utf8');
  for (const m of src.matchAll(REF)) {
    const doc = resolveRef(m[1], m[2]);
    if (doc) codeLinks.get(doc).add(file);
    else problems.push(`unknown ref  ${repo(file)} names "blueprint ${m[1]}${m[2] ? `/${m[2]}` : ''}" — no such doc`);
  }
  if (!mapped.has(file)) problems.push(`not mapped   ${repo(file)} has no row in docs/blueprint/CODE_MAP/`);
}

const order = (a, b) => label(a).localeCompare(label(b));
let stale = 0;
for (const file of bpFiles) {
  const text = body(file).replace(/\s+$/, '');
  const n = text.split('\n').length;
  if (n > MAX_LINES) problems.push(`too long     ${repo(file)} has ${n} lines (max ${MAX_LINES} without the backlinks block)`);
  const docs = [...docLinks.get(file)].sort(order).map((t) => `[${label(t)}](${rel(file, t)})`);
  const code = [...codeLinks.get(file)].sort(order).map((t) => `[\`${repo(t)}\`](${rel(file, t)})`);
  const isHub = existsSync(file.slice(0, -3));
  const isIndex = isCodeMap(file) || isTopics(file) || ['INDEX.md', 'REFERENCE.md'].includes(repo(file).slice(15));
  const lines = [START, '', '---', '', `**Linked from:** ${docs.join(' · ') || '— (only its hub and the indexes)'}`];
  if (code.length || !isIndex) lines.push('', `**Code:** ${code.join(' · ') || (isHub ? '— see its parts' : '— (not built yet)')}`);
  const block = [...lines, END].join('\n');
  const next = `${text}\n\n${block}\n`;
  if (next !== read(file)) { stale++; if (!CHECK) writeFileSync(file, next); }
}

for (const p of problems) console.log(p);
if (CHECK) {
  if (stale) console.log(`${stale} blueprint file(s) have stale backlinks — run: node scripts/gen-backlinks.mjs`);
  process.exit(stale || problems.length ? 1 : 0);
}
console.log(`backlinks: ${stale} file(s) updated, ${bpFiles.length} blueprint files, ${srcFiles.length} source files, ${problems.length} problem(s)`);
